/**
 * MockResults.jsx
 * frontend/admin-dashboard/src/pages/MockResults.jsx
 *
 * Basic 9 BECE-style mock exam score entry. Separate from Results.jsx
 * (term results) because mocks use a single raw /100 score per subject
 * (no reopen/ca/exams breakdown) and BECE grading (1-9, lower=better,
 * different cut points than the in-term report — see grades.py).
 *
 * Flow: pick Class -> Mock -> Year, then enter a raw score per subject
 * per student. Each (student, subject) cell auto-shows the BECE grade as
 * you type. "Save Changes" bulk-saves only the cells that were touched.
 *
 * Best six = English, Mathematics, Social Studies and Integrated Science
 * (all four core subjects) + the student's best two other subjects.
 * Mirrors backend mock_scoring.py:compute_mock_aggregate. If a core subject
 * has no score yet, the aggregate is shown with a "*" (provisional).
 *
 * This page only shows and saves scores for the 10 standard BECE subjects
 * (see BECE_SUBJECTS below) — any other subjects in the school's subject
 * list are left out of this screen entirely.
 *
 * Subject matching is tolerant: names are normalised (case, punctuation,
 * "&" vs "and") and matched against aliases, first exactly, then as whole
 * words inside the DB name (e.g. "Religious and Moral Education (RME)").
 *
 * PDFs are generated by the backend (school logo, motto, photo, styling):
 *   - "Download PDF" (toolbar): class broadsheet.
 *   - "PDF" (next to each student): individual report.
 * Both are built from SAVED scores, so unsaved edits must be saved first.
 */

